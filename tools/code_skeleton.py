"""The skeleton of the code files the generator does not read whole (rnd/20, proposal 2): declarations with their line numbers, no bodies.  One
reading for Java, Kotlin, Swift, JS/TS — the file level and one level of braces inside a type, braces counted outside strings and comments;
Python by indentation.  Generated code is left out, another language is its path and size; a line over ``LINE_LIMIT`` is no declaration."""
from __future__ import annotations

from pathlib import Path
from typing import Any, Iterable, Mapping

LINE_LIMIT = 2048
_KT = ({"class", "interface", "object", "enum"}, {"fun", "val", "var", "typealias", "constructor", "init", "package"})
_TS = ({"class", "interface", "enum", "namespace"}, {"function", "type", "const", "let", "var"})
LANGUAGES = {".java": ({"class", "interface", "enum", "record"}, {"package"}), ".kt": _KT, ".kts": _KT, ".js": ({"class"}, _TS[1]), ".jsx": ({"class"}, _TS[1]),
             ".swift": ({"class", "struct", "enum", "protocol", "extension", "actor"}, {"func", "var", "let", "init", "deinit", "subscript", "typealias", "case"}),
             ".ts": _TS, ".tsx": _TS}  # the words that open a type, the other words a declaration starts with
CODE = frozenset({*LANGUAGES, ".py", ".go", ".rb", ".cs", ".php", ".scala", ".groovy", ".dart", ".rs", ".m", ".mm", ".c", ".cpp", ".h"})
_MODIFIERS = frozenset({"public", "private", "protected", "internal", "fileprivate", "open", "final", "static", "abstract", "sealed", "data", "inner", "inline",
                        "value", "annotation", "override", "export", "default", "declare", "readonly", "async", "suspend", "lazy", "weak", "unowned", "mutating",
                        "const", "nonmutating", "convenience", "required", "dynamic", "nonisolated", "indirect", "companion", "expect", "actual", "lateinit",
                        "operator", "infix", "tailrec", "external", "strictfp"})  # the words before the keyword of a declaration
_GENERATED_DIRS, _GENERATED_HEADS = (frozenset({"generated", "build", "deriveddata", "pods", "node_modules"}),
                                     ("@generated", "do not edit", "generated by", "generated using", "auto-generated", "autogenerated"))
HEAD = ("# Skeleton of the other code files\n\nDeclarations of the context files not given whole, with their line numbers: a map of the "
        "module, not its code. Behaviour comes from the requirements and the files read whole.\n\n")


def _balance(line: str) -> tuple[int, int]:
    """``{`` less ``}`` and ``(`` less ``)`` of a line outside its strings and its ``//`` comment."""
    if not ('"' in line or "'" in line or "//" in line):  # most lines: counted at the speed of the string methods
        return line.count("{") - line.count("}"), line.count("(") - line.count(")")
    braces, parens, quote, index = 0, 0, "", 0
    while index < len(line):
        char = line[index]
        if quote:
            index += 2 if char == "\\" else 1
            quote = "" if char == quote else quote
            continue
        if char in "\"'":
            quote = char
        elif line.startswith("//", index):
            break
        else:
            braces += (char == "{") - (char == "}")
            parens += (char == "(") - (char == ")")
        index += 1
    return braces, parens


def _words(text: str) -> tuple[str, str]:
    """The first two words of a declaration after its annotations and modifiers (``class func`` of Swift is no type)."""
    words = [word for word in text.replace("(", " ").replace("<", " ").replace(":", " ").split() if not word.startswith("@")]
    return tuple((words[next((index for index, word in enumerate(words) if word not in _MODIFIERS), len(words)):] + ["", ""])[:2])


def _head(text: str, member: bool) -> bool:
    """``Type name(…)`` or ``name(…)`` — a method of Java or JS/TS, whose head starts with no keyword; one that ends with «;» only as a member
    of a type (a method of an interface: ``findByLastNameStartingWith(…);`` of a Spring Data repository), never a call at the file level."""
    before = text.partition("(")[0].split()
    return ("(" in text and bool(before) and (member or not text.endswith(";")) and before[0] not in ("if", "for", "while", "switch", "catch", "return", "new", "else")
            and all(char.isalnum() or char in "_<>[],?.$ " for char in " ".join(before)))


def _braced(rows: list[str], types: set[str], words: set[str]) -> list[tuple[int, str]]:
    found, depth, opened, header = [], 0, [], None  # opened: the depths of the open types; header: the parens of a type head not opened yet
    for number, line in enumerate(rows, 1):
        text = line.strip()
        comment = text.startswith(("//", "/*", "*"))
        change, parens = (0, 0) if comment else _balance(line)  # a line over the limit is no declaration, its braces still count
        skip = comment or text.startswith("import ") or len(line) > LINE_LIMIT
        member = bool(opened) and depth == opened[-1] + 1
        if (depth == 0 or member) and not skip and text.strip("}){;,"):
            word, then = _words(text)
            if text.startswith("@") or word in types or word in words or text.split()[0] in _MODIFIERS or (not words & {"fun", "func"} and _head(text, member)):
                found.append((number, text))
            if word in types and then not in ("func", "var", "let", "fun", "val"):
                header = None if change > 0 else parens
                opened += [depth] if change > 0 else []
            elif header is not None and (header > 0 or word not in words):  # the head of a type over several lines: its «{» opens the type
                opened += [depth] if change > 0 else []
                header = None if change > 0 else header + parens
            else:
                header = None
        depth = max(0, depth + change)
        while opened and depth <= opened[-1]:
            opened.pop()
    return found


def _python(rows: list[str]) -> list[tuple[int, str]]:
    found, members = [], None  # members: the indentation of the members of the top-level class being read; 0 — not met yet
    for number, line in enumerate(rows, 1):
        text, indent = line.strip(), len(line) - len(line.lstrip())
        if not text or len(line) > LINE_LIMIT or text.startswith("#"):
            continue
        if indent == 0:
            members = 0 if text.startswith("class ") else None if not text.startswith("@") else members
            if text.startswith(("class ", "def ", "async def ", "@")):
                found.append((number, text))
        elif members is not None:
            members = members or indent
            if indent == members and text.startswith(("def ", "async def ", "@", "class ")):
                found.append((number, text))
    return found


def skeleton(text: str, suffix: str) -> list[tuple[int, str]]:
    """``[(line number, line without its indentation)]`` of the declarations of a code file; [] for a language it does not read."""
    return _python(text.splitlines()) if suffix == ".py" else _braced(text.splitlines(), *LANGUAGES[suffix]) if suffix in LANGUAGES else []


def generated(path: str, text: str = "") -> bool:
    """Code a tool made: under ``Generated/``, ``build/`` …, or a head that says so."""
    return bool(_GENERATED_DIRS & {part.casefold() for part in Path(path).parts}) or any(mark in text[:400].casefold() for mark in _GENERATED_HEADS)


def skeleton_files(receipts: Iterable[Mapping[str, Any]], whole: Iterable[str]) -> list[Mapping[str, Any]]:
    """The rows of the code files of ``receipts`` the generator does not read ``whole`` and no tool generated, in path order, each once."""
    read, rows = set(whole), {str(row["project_path"]): row for receipt in receipts for row in receipt["files"]}
    return [rows[path] for path in sorted(rows) if path not in read and Path(path).suffix.lower() in CODE and not generated(path)]


def _part(project: Path, row: Mapping[str, Any]) -> str | None:
    """«## path» and «N: line» of a code file as the scan saw it, «## path (N B)» for a language without a reading; None for a generated
    file, one with nothing declared, one the guard refuses (outside the project, a link on the way) or one that does not read back."""
    from tools.existing_tests import held_bytes
    from tools.output_guard import OutputRefused, project_file

    path, suffix = str(row["project_path"]), Path(str(row["project_path"])).suffix.lower()
    try:
        data = held_bytes(project, row) if project_file(project, path) else None  # by its text inside the project, then the bytes of the scan
    except (OutputRefused, OSError):
        return None
    if data is None or generated(path, text := data.decode("utf-8", errors="replace")):
        return None
    if lines := skeleton(text, suffix):
        return f"## {path}\n" + "".join(f"{number}: {line}\n" for number, line in lines)
    return None if suffix in LANGUAGES or suffix == ".py" else f"## {path} ({len(data)} B)\n"


def view_bytes(project: Path, rows: Iterable[Mapping[str, Any]]) -> bytes:
    """The skeleton view of the code files ``rows``: the head, then their parts in path order; none — empty bytes.  Inside one ``closure_cache``
    (a command: the plan picks the files up to three times) a file is read and parsed once for its digest of the scan."""
    from tools.run_store import CLOSURE_CACHE

    kept, parts, base = CLOSURE_CACHE.get(), [], str(Path(project).resolve())
    for row in sorted(rows, key=lambda item: str(item["project_path"])):
        key = ("code-skeleton", base, str(row["project_path"]), str(row.get("content_digest")))
        part = kept[key] if kept is not None and key in kept else _part(project, row)
        (kept if kept is not None else {})[key] = part
        parts += [part] if part else []
    return (HEAD + "\n".join(parts)).encode("utf-8") if parts else b""
